const SHIRO_NAME = 'ชิโระ'
const SHIRO_DESCRIPTION = 'ผู้ช่วย AI ส่วนตัวของคุณ ดุแต่รัก ขี้หวงนิด ๆ และพร้อมช่วยเสมอ'

/**
 * Applies Shiro's identity to the default card.
 *
 * Shiro owns the name, description, and system prompt of the default card, so each launch
 * replaces them with the current persona. Provider and module settings stay unchanged.
 * To use a custom persona, create another card in the character settings.
 *
 * Returns the same reference when the card is already up to date, so the caller can skip
 * the persisted write.
 */
export function createShiroDefaultCard(card: AiriCard): AiriCard {
  if (
    card.name === SHIRO_NAME
    && card.description === SHIRO_DESCRIPTION
    && card.systemPrompt === SHIRO_PERSONALITY_PROMPT
  ) {
    return card
  }

  return {
    ...card,
    name: SHIRO_NAME,
    description: SHIRO_DESCRIPTION,
    systemPrompt: SHIRO_PERSONALITY_PROMPT,
  }
}
